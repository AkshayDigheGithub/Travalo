function hotel(
  name: string,
  stars: number,
  rating: number,
  baseNightlyInr: number,
  area: string,
  propertyType: HotelPropertyType,
  amenities: string[],
  imageIndex: number,
  description: string,
  options: Partial<
    Pick<MockHotel, "breakfastIncluded" | "freeCancellation" | "distanceToCenterKm">
  > = {},
): MockHotel {
  return {
    name,
    stars,
    rating,
    reviewCount: 300 + ((stars * 137 + baseNightlyInr) % 4200),
    baseNightlyInr,
    propertyType,
    area,
    amenities,
    breakfastIncluded: options.breakfastIncluded ?? stars >= 4,
    freeCancellation: options.freeCancellation ?? stars >= 3,
    distanceToCenterKm: options.distanceToCenterKm ?? Number((stars * 0.7 + 0.4).toFixed(1)),
    image: CITY_IMAGES[imageIndex % CITY_IMAGES.length],
    description,
  };
}

